// Детерминированный мини-рандом (LCG из Numerical Recipes): раскладка кучи
// базара, шум звука, политики тестов. Партию сдаёт генератор rng.ts
// (mulberry32) — его сюда не тянуть и этим не подменять.

/** Генератор чисел в [0, 1) по seed: один seed — одна последовательность. */
export function lcg(seed: number): () => number {
  let s = seed >>> 0;
  return () => {
    s = (Math.imul(s, 1664525) + 1013904223) >>> 0;
    return s / 4294967296;
  };
}
